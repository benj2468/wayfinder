/// Ask a provider to admit this node to its mesh, installing the certificate if
/// one is issued.
///
/// The one call here that reaches a node other than this dashboard's own: it
/// opens a short-lived anonymous connection to the provider, submits a CSR for
/// the identity *this* node already holds, and installs what comes back. See
/// [`crate::enroll`] for why it is the node's existing identity being certified
/// rather than a fresh one.
///
/// Call it again with the same arguments to collect a certificate that was held
/// for approval; re-submitting an identical request is how the provider is
/// polled, and does not queue a second one.
#[allow(missing_docs, reason = "request struct fields generated by #[server]")]
#[server(name = RequestEnrollment, prefix = "/api", endpoint = "request_enrollment")]
pub async fn request_enrollment(
    provider: ProviderTarget,
) -> Result<EnrollmentOutcome, ServerFnError> {
    let conn = connection()?;
    crate::enroll::request(&conn, &provider)
        .await
        .map_err(|e| ServerFnError::new(format!("{e:#}")))
}

