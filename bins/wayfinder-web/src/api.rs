/// Create a user account on a provider-mode node, returning the `otpauth://`
/// enrolment URI for its second factor (empty when created without one).
///
/// The URI comes back exactly once and is not recoverable afterwards, so the
/// caller must show it to the operator there and then.
///
/// The password crosses two hops: this browser to this server, and this server
/// to the node over authenticated TLS. Neither is stored — the authority keeps
/// only an Argon2id hash — and the second hop requires an administrator's
/// session, which is what makes the first hop's exposure bounded.
#[allow(missing_docs, reason = "request struct fields generated by #[server]")]
#[server(name = CreateUser, prefix = "/api", endpoint = "create_user")]
pub async fn create_user(
    username: String,
    password: String,
    admin: bool,
    session_ttl_secs: u64,
    no_totp: bool,
) -> Result<String, ServerFnError> {
    // Refused here as well as by the authority, so an obvious mistake reads as
    // itself rather than as a relayed wire error.
    if username.trim().is_empty() {
        return Err(ServerFnError::new("a user name is required"));
    }
    if password.is_empty() {
        return Err(ServerFnError::new("a password is required"));
    }

    connection()?
        .run(async |client| {
            client
                .create_user(username.trim(), &password, admin, session_ttl_secs, no_totp)
                .await
        })
        .await
        .map_err(|e| ServerFnError::new(format!("{e:#}")))
}

